where row_data.project_id is null
  and row_data.proj is not null;

insert into public.relation_migration_exceptions (
    table_name,
    row_id,
    relation_type,
    team_id,
    legacy_value,
    reason
)
select
    unresolved.table_name,
    unresolved.row_id,
    unresolved.relation_type,
    unresolved.team_id,
    unresolved.legacy_value,
    'No matching normalized record at V34 backfill'
from (
    select 'tasks' as table_name, id as row_id, 'player' as relation_type,
        team_id, member as legacy_value
    from public.tasks where member is not null and player_id is null
    union all
    select 'quests', id, 'player', team_id, member
    from public.quests where member is not null and player_id is null
    union all
    select 'attendance', id, 'player', team_id, member
    from public.attendance where member is not null and player_id is null
    union all
    select 'accessibility', id, 'player', team_id, member
    from public.accessibility where member is not null and player_id is null
    union all
    select 'tasks', id, 'project', team_id, proj
    from public.tasks where proj is not null and project_id is null
    union all
    select 'quests', id, 'project', team_id, proj
    from public.quests where proj is not null and project_id is null
    union all
    select 'accessibility', id, 'project', team_id, proj
    from public.accessibility where proj is not null and project_id is null
) unresolved
on conflict (table_name, row_id, relation_type) do update
set team_id = excluded.team_id,
    legacy_value = excluded.legacy_value,
    reason = excluded.reason;

-- Existing FK values are authoritative when a project or player was renamed.
update public.tasks row_data
set member = player.name
from public.players player
where row_data.player_id = player.id
  and row_data.member is distinct from player.name;

update public.quests row_data
