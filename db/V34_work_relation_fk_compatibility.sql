where row_data.player_id is null
  and row_data.member is not null;

update public.tasks row_data
set project_id = (
    select min(project.id)
    from public.projects project
    where project.team_id = row_data.team_id
      and project.name = row_data.proj
)
where row_data.project_id is null
  and row_data.proj is not null;

update public.quests row_data
set project_id = (
    select min(project.id)
    from public.projects project
    where project.team_id = row_data.team_id
      and project.name = row_data.proj
)
where row_data.project_id is null
  and row_data.proj is not null;

update public.accessibility row_data
set project_id = (
    select min(project.id)
    from public.projects project
    where project.team_id = row_data.team_id
      and project.name = row_data.proj
