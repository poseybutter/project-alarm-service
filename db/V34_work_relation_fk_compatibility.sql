revoke all on function public.sync_player_reference() from public;
revoke all on function public.sync_project_reference() from public;

do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'tasks',
        'quests',
        'attendance',
        'accessibility'
    ] loop
        execute format(
            'drop trigger if exists %I on public.%I',
            table_name || '_sync_player_reference',
            table_name
        );
        execute format(
            'create trigger %I before insert or update of team_id, member, player_id on public.%I for each row execute function public.sync_player_reference()',
            table_name || '_sync_player_reference',
            table_name
        );
    end loop;

    foreach table_name in array array[
        'tasks',
        'quests',
        'accessibility'
    ] loop
        execute format(
            'drop trigger if exists %I on public.%I',
            table_name || '_sync_project_reference',
            table_name
        );
        execute format(
            'create trigger %I before insert or update of team_id, proj, project_id on public.%I for each row execute function public.sync_project_reference()',
            table_name || '_sync_project_reference',
            table_name
        );
    end loop;
end;
$$;

create or replace function public.propagate_player_reference_name()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.name is distinct from old.name then
        update public.tasks set member = new.name where player_id = new.id;
        update public.quests set member = new.name where player_id = new.id;
        update public.attendance set member = new.name where player_id = new.id;
        update public.accessibility set member = new.name where player_id = new.id;
    end if;
    return new;
end;
$$;

create or replace function public.prevent_referenced_player_team_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.team_id is distinct from old.team_id
       and (
           exists (select 1 from public.tasks where player_id = old.id)
           or exists (select 1 from public.quests where player_id = old.id)
           or exists (select 1 from public.attendance where player_id = old.id)
           or exists (select 1 from public.accessibility where player_id = old.id)
       ) then
        raise exception 'Referenced player cannot move to another team'
            using errcode = '23503';
    end if;
    return new;
end;
$$;

create or replace function public.propagate_project_reference_name()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.name is distinct from old.name then
        update public.tasks set proj = new.name where project_id = new.id;
        update public.quests set proj = new.name where project_id = new.id;
        update public.accessibility set proj = new.name where project_id = new.id;
    end if;
    return new;
end;
$$;

create or replace function public.prevent_referenced_project_team_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.team_id is distinct from old.team_id
       and (
           exists (select 1 from public.tasks where project_id = old.id)
           or exists (select 1 from public.quests where project_id = old.id)
           or exists (select 1 from public.accessibility where project_id = old.id)
       ) then
        raise exception 'Referenced project cannot move to another team'
            using errcode = '23503';
    end if;
    return new;
end;
$$;

revoke all on function public.propagate_player_reference_name() from public;
revoke all on function public.propagate_project_reference_name() from public;
revoke all on function public.prevent_referenced_player_team_change() from public;
revoke all on function public.prevent_referenced_project_team_change() from public;

drop trigger if exists players_prevent_referenced_team_change on public.players;
create trigger players_prevent_referenced_team_change
before update of team_id on public.players
for each row execute function public.prevent_referenced_player_team_change();

drop trigger if exists projects_prevent_referenced_team_change on public.projects;
create trigger projects_prevent_referenced_team_change
before update of team_id on public.projects
for each row execute function public.prevent_referenced_project_team_change();

drop trigger if exists players_propagate_reference_name on public.players;
create trigger players_propagate_reference_name
after update of name on public.players
for each row execute function public.propagate_player_reference_name();

drop trigger if exists projects_propagate_reference_name on public.projects;
create trigger projects_propagate_reference_name
after update of name on public.projects
for each row execute function public.propagate_project_reference_name();

commit;
