create or replace function public.sync_player_reference()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    resolved_player public.players%rowtype;
    legacy_name_changed boolean;
begin
    if tg_op = 'UPDATE' then
        legacy_name_changed := (
            new.member is distinct from old.member
            or new.team_id is distinct from old.team_id
        )
        and new.player_id is not distinct from old.player_id;
    else
        legacy_name_changed := false;
    end if;

    if new.member is null and new.player_id is null then
        delete from public.relation_migration_exceptions
        where table_name = tg_table_name
          and row_id = new.id
          and relation_type = 'player';
        return new;
    end if;

    if tg_op = 'UPDATE'
       and old.player_id is not null
       and new.player_id is null
       and new.member is not distinct from old.member
       and new.team_id is not distinct from old.team_id then
        insert into public.relation_migration_exceptions (
            table_name,
            row_id,
            relation_type,
            team_id,
            legacy_value,
            reason
        ) values (
            tg_table_name,
            new.id,
            'player',
            new.team_id,
            new.member,
            'Normalized player record was removed'
        )
        on conflict (table_name, row_id, relation_type) do update
        set team_id = excluded.team_id,
            legacy_value = excluded.legacy_value,
            reason = excluded.reason;
        return new;
    end if;

    if new.player_id is null or legacy_name_changed then
        select * into resolved_player
        from public.players player
        where player.team_id = new.team_id
          and player.name = new.member
        order by player.id
        limit 1;
    else
        select * into resolved_player
        from public.players player
        where player.id = new.player_id
          and player.team_id = new.team_id;
    end if;

    if not found then
        raise exception 'Player reference is not valid for team %', new.team_id
            using errcode = '23503';
    end if;

    if new.member is not null and new.member is distinct from resolved_player.name then
        raise exception 'Player name does not match player_id for team %', new.team_id
            using errcode = '23503';
    end if;

    new.player_id := resolved_player.id;
    new.member := resolved_player.name;
    delete from public.relation_migration_exceptions
    where table_name = tg_table_name
      and row_id = new.id
      and relation_type = 'player';
    return new;
end;
$$;

