-- Add and maintain normalized player/project references without removing the
-- legacy member/proj columns used by the current Next.js client.

begin;

create table if not exists public.relation_migration_exceptions (
    id bigint generated by default as identity primary key,
    table_name text not null
        check (table_name in ('tasks', 'quests', 'attendance', 'accessibility')),
    row_id bigint not null,
    relation_type text not null
        check (relation_type in ('player', 'project')),
    team_id text,
    legacy_value text,
    reason text not null,
    created_at timestamptz not null default now(),
    unique (table_name, row_id, relation_type)
);

alter table public.relation_migration_exceptions enable row level security;
revoke all on public.relation_migration_exceptions from public, anon, authenticated;
grant all on public.relation_migration_exceptions to service_role;
grant usage, select on sequence public.relation_migration_exceptions_id_seq
    to service_role;

-- Legacy clients resolve relations by team and display name, so that pair must
-- stay unambiguous until every write path sends normalized IDs.
do $$
begin
    if exists (
        select 1 from public.players
        where team_id is not null
        group by team_id, name having count(*) > 1
    ) then
        raise exception 'Duplicate player names exist within a team'
            using errcode = '23505';
    end if;
    if exists (
        select 1 from public.projects
        where team_id is not null
        group by team_id, name having count(*) > 1
    ) then
        raise exception 'Duplicate project names exist within a team'
            using errcode = '23505';
    end if;
end;
$$;

create unique index if not exists players_team_name_uidx
    on public.players (team_id, name);
create unique index if not exists projects_team_name_uidx
    on public.projects (team_id, name);

do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'tasks',
        'quests',
        'attendance',
        'accessibility'
    ] loop
        execute format(
            'alter table public.%I add column if not exists player_id bigint',
            table_name
        );

        if not exists (
            select 1
            from pg_constraint constraint_row
            join pg_attribute attribute_row
              on attribute_row.attrelid = constraint_row.conrelid
             and attribute_row.attnum = any (constraint_row.conkey)
            where constraint_row.conrelid = format('public.%I', table_name)::regclass
              and constraint_row.contype = 'f'
              and constraint_row.confrelid = 'public.players'::regclass
              and attribute_row.attname = 'player_id'
        ) then
            execute format(
                'alter table public.%I add constraint %I foreign key (player_id) references public.players(id) on update cascade on delete set null',
                table_name,
                table_name || '_player_id_fkey'
            );
        end if;

        execute format(
            'create index if not exists %I on public.%I (team_id, player_id)',
            table_name || '_team_player_idx',
            table_name
        );
    end loop;

    foreach table_name in array array[
        'tasks',
        'quests',
        'accessibility'
    ] loop
        execute format(
            'alter table public.%I add column if not exists project_id bigint',
            table_name
        );

        if not exists (
            select 1
            from pg_constraint constraint_row
            join pg_attribute attribute_row
              on attribute_row.attrelid = constraint_row.conrelid
             and attribute_row.attnum = any (constraint_row.conkey)
            where constraint_row.conrelid = format('public.%I', table_name)::regclass
              and constraint_row.contype = 'f'
              and constraint_row.confrelid = 'public.projects'::regclass
              and attribute_row.attname = 'project_id'
        ) then
            execute format(
                'alter table public.%I add constraint %I foreign key (project_id) references public.projects(id) on update cascade on delete set null',
                table_name,
                table_name || '_project_id_fkey'
            );
        end if;

        execute format(
            'create index if not exists %I on public.%I (team_id, project_id)',
            table_name || '_team_project_idx',
            table_name
        );
    end loop;
end;
$$;

update public.tasks row_data
set player_id = (
    select min(player.id)
    from public.players player
    where player.team_id = row_data.team_id
      and player.name = row_data.member
)
where row_data.player_id is null
  and row_data.member is not null;

update public.quests row_data
set player_id = (
    select min(player.id)
    from public.players player
    where player.team_id = row_data.team_id
      and player.name = row_data.member
)
where row_data.player_id is null
  and row_data.member is not null;

update public.attendance row_data
set player_id = (
    select min(player.id)
    from public.players player
    where player.team_id = row_data.team_id
